local api = require('logic.api')

local KEYS = { 'superior', 'ultra', 'hyper', 'absolute' }

describe('API ShmAdvancedBelts', function()
  it('configure копит переопределения тира', function()
    local instance = api.new(KEYS)
    instance.configure('hyper', { speed = 120 })
    instance.configure('hyper', { color = { 1, 2, 3 } })
    local overrides = instance._take()
    assert_eq(overrides.hyper.speed, 120)
    assert_eq(overrides.hyper.color, { 1, 2, 3 })
  end)

  it('повторный configure сливает рецепты по частям', function()
    local instance = api.new(KEYS)
    instance.configure('ultra', { recipes = { belt = { previous = 2 } } })
    instance.configure('ultra', { recipes = { splitter = { previous = 3 } } })
    local overrides = instance._take()
    assert_eq(overrides.ultra.recipes.belt.previous, 2)
    assert_eq(overrides.ultra.recipes.splitter.previous, 3)
  end)

  it('set_enabled выключает тир', function()
    local instance = api.new(KEYS)
    instance.set_enabled('ultra', false)
    assert_false(instance._take().ultra.enabled)
  end)

  it('неизвестный тир — ошибка', function()
    local instance = api.new(KEYS)
    assert_error(function()
      instance.configure('mega', { speed = 1 })
    end, 'неизвестный тир')
  end)

  it('неизвестное поле — ошибка', function()
    local instance = api.new(KEYS)
    assert_error(function()
      instance.configure('hyper', { sped = 1 })
    end, 'неизвестное поле')
  end)

  it('поле не того типа — ошибка', function()
    local instance = api.new(KEYS)
    assert_error(function()
      instance.configure('hyper', { speed = 'fast' })
    end, 'должно быть number')
  end)

  it('неизвестный рецепт — ошибка', function()
    local instance = api.new(KEYS)
    assert_error(function()
      instance.configure('hyper', { recipes = { pipe = {} } })
    end, 'неизвестный рецепт')
  end)

  it('после сборки API закрыт', function()
    local instance = api.new(KEYS)
    instance._take()
    assert_error(function()
      instance.configure('hyper', { speed = 120 })
    end, 'data.lua')
  end)
end)
